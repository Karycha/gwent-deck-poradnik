import re
def auto_tip(c):
    ab = c["ab"]
    if "Zdrada" in ab: return ("R1", "Szpieg: daje przewagę kart, dobry w pierwszej rundzie.")
    if c["t"] in ("S","A") and re.search(r"Zadaj|Zniszcz|Zablokuj|Wygnaj|Przechwyć|Pochłoń", ab):
        return ("ODP", "Trzymaj na groźną jednostkę albo silnik rywala.")
    if re.search(r"Rozkaz|Na koniec (swojej|sojuszniczej|każdej|twojej) tury|Za każdym razem|Ilekroć|Pokrzepienie|Asymilacja|Harmonia", ab):
        return ("SIL", "Silnik: graj wcześnie w długiej rundzie, żeby zebrał wartość.")
    if re.search(r"[Zz]agraj.*z (swojej )?talii|[Ww]ezwij.*z (swojej )?talii|[Dd]obierz", ab):
        return ("COMBO", "Ciągnie karty z talii. Graj, gdy cel jest jeszcze w talii.")
    if c["g"] and c["p"] >= 10: return ("FIN", "Mocna karta na R3 albo na zamknięcie rundy.")
    if re.search(r"Zadaj|Zniszcz", ab): return ("ODP", "Kontrola: użyj na zagrożenie, nie na zwykłe punkty.")
    return ("WYP", "Tempo: zagraj, gdy potrzebujesz punktów.")
